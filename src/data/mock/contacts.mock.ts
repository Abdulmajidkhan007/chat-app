export interface ContactSection {
  letter: string;
  data: UserPreview[];
}

// Group contacts by first letter and sort alphabetically
export const mockContactSections: ContactSection[] = (() => {
  const grouped = mockContacts.reduce(
    (acc, contact) => {
      const letter = contact.firstName.charAt(0).toUpperCase();
      if (!acc[letter]) {
        acc[letter] = [];
      }
      acc[letter].push(contact);
      return acc;
    },
    {} as Record<string, UserPreview[]>
  );

  return Object.keys(grouped)
    .sort()
    .map((letter) => ({
      letter,
      data: (grouped[letter] ?? []).sort((a, b) => a.firstName.localeCompare(b.firstName)),
    }));
})();
