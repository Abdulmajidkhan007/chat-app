// Helper to create a last message for a chat
const createLastMessage = (chatId: string, senderId: string, text: string, hoursAgo: number): ChatMessage => ({
  id: `last_msg_${chatId}`,
  chatId,
  senderId,
  senderPreview: mockUsersMap[senderId]!,
  type: 'text',
  text,
  status: 'read' as const,
  sentAt: new Date(Date.now() - hoursAgo * 60 * 60 * 1000),
  isDeleted: false,
  isPinned: false,
  replyTo: null,
  reactions: [],
});

